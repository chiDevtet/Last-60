beforeAll(startDb, 120_000);
afterAll(stopDb);

const vaultPath = () => join(mkdtempSync(join(tmpdir(), "l60vault-")), "sub", "wallet-vault.key");
const MAINNET = { SOLANA_CLUSTER: "mainnet-beta", SOLANA_RPC_URL: "https://api.mainnet-beta.solana.com", MONGODB_URI: "mongodb://x", LAUNCH_PROVIDER: "raydium_launchlab", SCHEDULE_ENCRYPTION_KEY: Buffer.alloc(32, 7).toString("base64") };

describe("LaunchLab pool derived from the token mint (before launch)", () => {
  test("the PDA [pool, mint, WSOL] reproduces a real LaunchLab pool", () => {
    // The fixture's base mint (a real migrated mainnet token) → its real bonding pool.
    expect(deriveLaunchLabPool(lM.baseMint)).toBe(llFx.bondingPool);
    expect(() => deriveLaunchLabPool("not-a-key")).toThrow();
  });

  test("config and runtime settings derive the pool; an explicit pool wins; a token set in the admin console follows its own pool", () => {
    const pool = llFx.bondingPool as string;
    const c = loadConfig("indexer", { ...MAINNET, TOKEN_MINT: lM.baseMint });
    expect(c.provider).toMatchObject({ poolAddress: pool, poolAddressSource: "derived" });
    expect(resolveSettings(c, {}, 1)).toMatchObject({ tokenMint: lM.baseMint, poolAddress: pool, poolAddressSource: "derived" });
    // A token chosen in the admin console never inherits the environment's pool of another token.
    const other = Keypair.generate().publicKey.toBase58();
    expect(resolveSettings(c, { tokenMint: other }, 2)).toMatchObject({ poolAddress: deriveLaunchLabPool(other), poolAddressSource: "derived" });
    const explicit = Keypair.generate().publicKey.toBase58();
    expect(resolveSettings(c, { tokenMint: other, poolAddress: explicit }, 3)).toMatchObject({ poolAddress: explicit, poolAddressSource: "configured" });
    // Nothing configured yet: the workers start and wait.
    const empty = loadConfig("rewards", MAINNET);
    expect(resolveSettings(empty, {}, 1)).toMatchObject({ tokenMint: null, poolAddress: null });
  });

  test("before launch the provider reports a waiting state, not a failure", async () => {
    expect(() => createProvider({ id: "raydium_launchlab", poolAddress: null, tokenMint: null, role: "creator", payoutMint: "So11111111111111111111111111111111111111112", expected: {} as any }, null)).toThrow(AwaitingLaunchError);
    const mint = Keypair.generate().publicKey.toBase58();
    const p = createProvider({ id: "raydium_launchlab", poolAddress: deriveLaunchLabPool(mint), tokenMint: mint, role: "creator", payoutMint: "So11111111111111111111111111111111111111112", expected: {} as any }, new FakeChain());
    await expect(p.load()).rejects.toBeInstanceOf(AwaitingLaunchError);
  });
});

describe("wallet vault: generated by the rewards worker, stored encrypted, loaded at boot", () => {
  test("generate → encrypted at rest (no key in the database) → addresses complete every process's config → the rewards worker decrypts", async () => {
    const db = await freshDb();
    const path = vaultPath();
    const cfg = loadConfig("rewards", { ...MAINNET, LAST60_WALLET_VAULT_KEY_PATH: path });
    expect(cfg.wallets.payout.source).toBeNull();
    for (const role of ["payout", "creator"]) expect(await requestWalletGeneration(db, cfg, { role, actor: "admin" })).toMatchObject({ status: "requested", created: true });
    expect(await requestWalletGeneration(db, cfg, { role: "payout", actor: "admin" })).toMatchObject({ status: "requested", created: false }); // idempotent while pending
    // Two leaders racing: each wallet is generated exactly once.
    const [a, b] = await Promise.all([fulfilWalletRequests(db, cfg), fulfilWalletRequests(db, cfg)]);
    expect([...a, ...b].sort()).toEqual(["creator", "payout"]);
    expect(statSync(path).mode & 0o777).toBe(0o600);
    expect(statSync(join(path, "..")).mode & 0o777).toBe(0o700);
    const vault = await readVaultWallets(db);
    expect(vault.payout).toBeTruthy();
    expect(vault.creator).toBeTruthy();
    // Decrypts to the recorded address; no form of the secret key is anywhere in the database.
    const payout = (await loadVaultKeypair(db, cfg, "payout"))!;
    const creator = (await loadVaultKeypair(db, cfg, "creator"))!;
    expect(payout.publicKey.toBase58()).toBe(vault.payout!);
    expect(creator.publicKey.toBase58()).toBe(vault.creator!);
    const dump = JSON.stringify(await db.WalletVault.find({}).lean());
    for (const kp of [payout, creator]) for (const form of [bs58.encode(kp.secretKey), JSON.stringify(Array.from(kp.secretKey)), Buffer.from(kp.secretKey).toString("base64"), Buffer.from(kp.secretKey).toString("hex")]) expect(dump.includes(form)).toBe(false);
    // Every process completes its configuration from the vault: payout destination, custody, creator automation.
    const full = loadConfig("rewards", { ...MAINNET, LAST60_WALLET_VAULT_KEY_PATH: path }, { vault });
    expect(full.wallets).toMatchObject({ payout: { address: vault.payout, source: "vault" }, creator: { address: vault.creator, source: "vault" } });
    expect(full.payout.walletPublicKey).toBe(vault.payout!);
    expect(full.revenue.fundingDestinations).toEqual([vault.payout!]);
    expect(full.revenue.custody).toMatchObject({ enabled: true, payoutWallet: vault.payout });
    expect(full.creatorWallet).toMatchObject({ address: vault.creator, keyConfigured: true, automationEnabled: true });
    expect(full.feeCollection.mode).toBe("auto_claim");
    expect(loadConfig("api", MAINNET, { vault }).wallets.payout.source).toBe("vault");
    // Live mode is allowed with a generated payout wallet (validated against the API's view, too).
    expect(loadConfig("rewards", { ...MAINNET, PAYOUT_MODE: "live", ALLOW_MAINNET_PAYOUTS: "true" }, { vault }).payout.mode).toBe("live");
    // A wallet is never replaced from the admin console.
    await expect(requestWalletGeneration(db, cfg, { role: "payout", actor: "admin" })).rejects.toThrow(/never replaced/);
  });

  test("fails closed: a missing / other / insecure vault key, a tampered entry, an environment wallet, a conflicting address", async () => {
    const db = await freshDb();
    const path = vaultPath();
    const cfg = loadConfig("rewards", { ...MAINNET, LAST60_WALLET_VAULT_KEY_PATH: path });
    await requestWalletGeneration(db, cfg, { role: "payout", actor: "admin" });
    await fulfilWalletRequests(db, cfg);
    const vault = await readVaultWallets(db);
    const elsewhere = loadConfig("rewards", { ...MAINNET, LAST60_WALLET_VAULT_KEY_PATH: vaultPath() });
    await expect(loadVaultKeypair(db, elsewhere, "payout")).rejects.toMatchObject({ code: "vault_key_missing" });
    const otherKey = loadConfig("rewards", { ...MAINNET, LAST60_WALLET_VAULT_KEY: Buffer.alloc(32, 9).toString("base64") });
    await expect(loadVaultKeypair(db, otherKey, "payout")).rejects.toMatchObject({ code: "vault_key_mismatch" });
    // Generating under another vault key is refused (it could not open the existing wallets).
    await requestWalletGeneration(db, otherKey, { role: "creator", actor: "admin" });
    await expect(fulfilWalletRequests(db, otherKey)).rejects.toMatchObject({ code: "vault_key_mismatch" });
    // A group-readable key file is refused.
    const loose = join(mkdtempSync(join(tmpdir(), "l60loose-")), "k");
    writeFileSync(loose, Buffer.alloc(32, 1).toString("base64"), { mode: 0o644 });
    expect(() => loadVaultKey(loadConfig("rewards", { ...MAINNET, LAST60_WALLET_VAULT_KEY_PATH: loose }))).toThrow(/readable by group/);
    // Tampering with the stored ciphertext (or swapping the address) is detected.
    const row: any = await db.WalletVault.findById("payout").lean();
    const ct = Buffer.from(row.ciphertext, "base64");
    ct[3] = ct[3]! ^ 1;
    await db.WalletVault.updateOne({ _id: "payout" }, { $set: { ciphertext: ct.toString("base64") } });
    await expect(loadVaultKeypair(db, cfg, "payout")).rejects.toMatchObject({ code: "vault_entry_corrupt" });
    await db.WalletVault.updateOne({ _id: "payout" }, { $set: { ciphertext: row.ciphertext, address: Keypair.generate().publicKey.toBase58() } });
    await expect(loadVaultKeypair(db, cfg, "payout")).rejects.toMatchObject({ code: "vault_entry_corrupt" });
    // An environment wallet is never shadowed by a generated one, and the two may not disagree.
    const env = loadConfig("rewards", { ...MAINNET, LAST60_PAYOUT_WALLET_ADDRESS: Keypair.generate().publicKey.toBase58() });
    await expect(requestWalletGeneration((await freshDb()), env, { role: "payout", actor: "admin" })).rejects.toBeInstanceOf(VaultError);
    expect(() => loadConfig("rewards", { ...MAINNET, LAST60_PAYOUT_WALLET_ADDRESS: Keypair.generate().publicKey.toBase58() }, { vault })).toThrow(/differs from the payout wallet generated/);
  });

  test("the rewards worker generates wallets before launch (no token yet) and reports 'waiting for launch'", async () => {
    const db = await freshDb();
    const cfg = testConfig({ LAUNCH_PROVIDER: "raydium_launchlab", LAST60_WALLET_VAULT_KEY_PATH: vaultPath() });
    const settings = new SettingsStore(db, cfg, 0);
    const worker = new RewardsWorker({ db, cfg, settings, payer: null, claimer: null, rpc: new FakeChain() });
    await requestWalletGeneration(db, cfg, { role: "creator", actor: "admin" });
    const ctrl = new AbortController();
    const running = worker.run(ctrl.signal);
    for (let i = 0; i < 100 && !(await readVaultWallets(db)).creator; i++) await new Promise((r) => setTimeout(r, 100));
    await new Promise((r) => setTimeout(r, 300));
    ctrl.abort();
    await running;
    expect((await readVaultWallets(db)).creator).toBeTruthy();
    expect(await db.TerminalEvent.countDocuments({ message: /waiting for launch: no token mint is configured/ })).toBe(1);
  });
});

describe("end-to-end encrypted key export, signed by an admin wallet", () => {
  async function setup(o: { rewardsAdmins?: string[] } = {}) {
    const db = await freshDb();
    const admin = Keypair.generate();
    const path = vaultPath();
    const env = { ...MAINNET, LAST60_WALLET_VAULT_KEY_PATH: path, ADMIN_WALLETS: (o.rewardsAdmins ?? [admin.publicKey.toBase58()]).join(",") };
    const cfg = loadConfig("rewards", env);
    await requestWalletGeneration(db, cfg, { role: "creator", actor: admin.publicKey.toBase58() });
    await fulfilWalletRequests(db, cfg);
    const address = (await readVaultWallets(db)).creator!;
    const sign = (message: string, who = admin) => bs58.encode(ed25519.sign(new TextEncoder().encode(message), who.secretKey.subarray(0, 32)));
    const intent = (o2: { expiresIn?: number; site?: string; role?: "payout" | "creator" } = {}) => {
      const req = newExportRequest();
      const message = exportIntentMessage({ site: o2.site ?? "last60.fun", role: o2.role ?? "creator", address, requestId: req.requestId, browserKey: req.browserKey, expiresAt: new Date(Date.now() + (o2.expiresIn ?? 120_000)).toISOString() });
      return { req, message };
    };
    return { db, admin, cfg, address, sign, intent };
  }

  test("only the requesting browser can open it; the API and database only ever hold ciphertext, delivered once", async () => {
    const { db, admin, cfg, address, sign, intent } = await setup();
    const { req, message } = intent();
    const A = admin.publicKey.toBase58();
    expect(await createExportRequest(db, cfg, "creator", { requestId: req.requestId, message, signature: sign(message), adminWallet: A, site: "last60.fun" })).toMatchObject({ accepted: true });
    expect(await takeExport(db, req.requestId, A)).toEqual({ status: "pending" });
    expect(await fulfilExportRequests(db, cfg)).toBe(1);
    const original = (await loadVaultKeypair(db, cfg, "creator"))!;
    const dump = JSON.stringify(await db.WalletExport.find({}).lean());
    expect(dump.includes(bs58.encode(original.secretKey))).toBe(false);
    expect(await takeExport(db, req.requestId, Keypair.generate().publicKey.toBase58())).toEqual({ status: "not_found" }); // another admin
    const t: any = await takeExport(db, req.requestId, A);
    expect(t).toMatchObject({ status: "ready", role: "creator", address });
    expect(Buffer.from(await openExport(req.secret, t.sealed, req.requestId)).equals(Buffer.from(original.secretKey))).toBe(true);
    // Another browser key cannot open it; a second read gets nothing; the ciphertext is gone.
    await expect(openExport(newExportRequest().secret, t.sealed, req.requestId)).rejects.toThrow();
    expect(await takeExport(db, req.requestId, A)).toEqual({ status: "consumed" });
    expect(((await db.WalletExport.findById(req.requestId).lean()) as any).ciphertext).toBeNull();
    expect(((await db.WalletVault.findById("creator").lean()) as any).exports).toBe(1);
  });

  test("refused: unsigned / wrong signer, another site, expired, replayed id, swapped browser key, signer not in the rewards worker's ADMIN_WALLETS", async () => {
    const { db, admin, cfg, sign, intent } = await setup();
    const A = admin.publicKey.toBase58();
    const ok = (m: string) => ({ message: m, signature: sign(m), adminWallet: A, site: "last60.fun" });
    let x = intent();
    expect(await createExportRequest(db, cfg, "creator", { requestId: x.req.requestId, ...ok(x.message), signature: sign(x.message, Keypair.generate()) })).toMatchObject({ accepted: false, reason: "bad_admin_signature" });
    expect(await createExportRequest(db, cfg, "creator", { requestId: x.req.requestId, ...ok(x.message), site: "evil.example" })).toMatchObject({ accepted: false, reason: "site_mismatch" });
    await expect(createExportRequest(db, cfg, "payout", { requestId: x.req.requestId, ...ok(x.message) })).rejects.toBeInstanceOf(VaultError); // no generated payout wallet
    x = intent({ expiresIn: -1_000 });
    expect(await createExportRequest(db, cfg, "creator", { requestId: x.req.requestId, ...ok(x.message) })).toMatchObject({ accepted: false, reason: "export_intent_expired" });
    x = intent({ expiresIn: 60 * 60_000 });
    expect(await createExportRequest(db, cfg, "creator", { requestId: x.req.requestId, ...ok(x.message) })).toMatchObject({ accepted: false, reason: "export_intent_expiry_too_far" });
    x = intent();
    expect(await createExportRequest(db, cfg, "creator", { requestId: x.req.requestId, ...ok(x.message) })).toMatchObject({ accepted: true });
    expect(await createExportRequest(db, cfg, "creator", { requestId: x.req.requestId, ...ok(x.message) })).toMatchObject({ accepted: false, reason: "request_id_reused" });
    // Someone with database access swaps in their own browser key: the worker refuses (it is not what the admin signed).
    await db.WalletExport.updateOne({ _id: x.req.requestId }, { $set: { browserKey: newExportRequest().browserKey } });
    await fulfilExportRequests(db, cfg);
    expect(await takeExport(db, x.req.requestId, A)).toMatchObject({ status: "refused", reason: "browser_key_mismatch" });
    // …or rewrites the message too: the signature no longer matches.
    x = intent();
    await createExportRequest(db, cfg, "creator", { requestId: x.req.requestId, ...ok(x.message) });
    const forged = intent().message.replace(/Request: .*/, `Request: ${x.req.requestId}`);
    await db.WalletExport.updateOne({ _id: x.req.requestId }, { $set: { message: forged, browserKey: forged.match(/Browser key: (.*)/)![1] } });
    await fulfilExportRequests(db, cfg);
    expect(await takeExport(db, x.req.requestId, A)).toMatchObject({ status: "refused", reason: "bad_admin_signature" });
    // The rewards worker trusts only its OWN admin list.
    const other = await setup({ rewardsAdmins: [Keypair.generate().publicKey.toBase58()] });
    const y = other.intent();
    const B = other.admin.publicKey.toBase58();
    await createExportRequest(other.db, other.cfg, "creator", { requestId: y.req.requestId, message: y.message, signature: other.sign(y.message), adminWallet: B, site: "last60.fun" });
    await fulfilExportRequests(other.db, other.cfg);
    expect(await takeExport(other.db, y.req.requestId, B)).toMatchObject({ status: "refused", reason: "signer_not_in_rewards_worker_admin_wallets" });
    const none = await setup({ rewardsAdmins: [] });
    const z = none.intent();
    const C = none.admin.publicKey.toBase58();
    await createExportRequest(none.db, none.cfg, "creator", { requestId: z.req.requestId, message: z.message, signature: none.sign(z.message), adminWallet: C, site: "last60.fun" });
    await fulfilExportRequests(none.db, none.cfg);
    expect(await takeExport(none.db, z.req.requestId, C)).toMatchObject({ status: "refused", reason: expect.stringContaining("admin_wallets_not_configured_in_rewards_worker") });
  });
});
